pub fn hex_to_rssi(hex_value: u8) -> i8 {
    match hex_value {
        0xC0..=0xFF => -92,
        0xBC..=0xBF => -91,
        0xBB => -90,
        0xB9..=0xBA => -89,
        0xB8 => -88,
        0xAE..=0xB7 => -87,
        0xA9..=0xAD => -86,
        0xA2..=0xA8 => -85,
        0x92..=0xA1 => -84,
        0x8D..=0x91 => -83,
        0x86..=0x8C => -82,
        0x82..=0x85 => -81,
        0x7D..=0x81 => -80,
        0x79..=0x7C => -79,
        0x75..=0x78 => -78,
        0x72..=0x74 => -77,
        0x6F..=0x71 => -76,
        0x6B..=0x6E => -75,
        0x68..=0x6A => -74,
        0x66..=0x67 => -73,
        0x63..=0x65 => -72,
        0x5F..=0x62 => -71,
        0x5B..=0x5E => -70,
        0x58..=0x5A => -69,
        0x54..=0x57 => -68,
        0x4F..=0x53 => -67,
        0x4B..=0x4E => -66,
        0x47..=0x4A => -65,
        0x43..=0x46 => -64,
        0x3D..=0x42 => -63,
        0x2A..=0x3C => -62,
        0x25..=0x29 => -60,
        0x1A..=0x24 => -58,
        0x16..=0x19 => -56,
        0x13..=0x15 => -54,
        0x11..=0x12 => -52,
        0x0E..=0x10 => -50,
        0x0D => -48,
        0x0C => -46,
        0x00..=0x0B => -44,
    }
}